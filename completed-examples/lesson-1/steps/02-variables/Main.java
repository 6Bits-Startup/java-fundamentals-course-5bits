public class Main {
    public static void main(String[] args) {
        // Variables: cajitas con nombre que guardan un dato
        String name = "Valeria";      // texto
        int age = 14;                 // número entero
        double height = 1.58;         // número con decimales
        boolean likesMusic = true;    // verdadero o falso
        char favoriteLetter = 'V';    // un solo carácter

        System.out.println("===== MI PERFIL =====");
        System.out.println("Nombre: " + name);
        System.out.println("Edad: " + age + " años");
        System.out.println("Estatura: " + height + " m");
        System.out.println("¿Le gusta la música? " + likesMusic);
        System.out.println("Letra favorita: " + favoriteLetter);
        System.out.println("=====================");
    }
}
